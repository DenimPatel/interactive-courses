#!/usr/bin/env node
/*
 * Give every content page the skip link's target.
 *
 * The skip link is injected by _includes/site-nav.html, which all ~283 part
 * pages include, and it points at #main. A page whose <main> carries no id
 * therefore gets a skip link that moves focus nowhere — the control looks
 * correct, it is keyboard-reachable, and it does nothing, which is worse than
 * not having it.
 *
 * 47 pages already have it (the hand-written-head set, done by
 * inject-theme-head.js). This does the remaining 255.
 *
 * Only the FIRST <main> in a file is touched, and only if the document does
 * not already declare id="main" somewhere — a second id="main" would be
 * invalid HTML and would make the link resolve to the first one anyway.
 *
 * Jekyll's generated redirect stubs are skipped: they have no <main> and are
 * meta-refresh pages, not documents.
 *
 * Usage: node scripts/inject-skip-target.js [--check]
 */
"use strict";

const fs = require("fs");
const path = require("path");

const CHECK_ONLY = process.argv.includes("--check");

function findPages(dir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) findPages(p, out);
    else if (entry.name.endsWith(".html")) out.push(p);
  }
  return out;
}

const pages = [];
// SOURCE pages, not _site: _site is deleted and regenerated by every build, so
// a change made there would not survive to the next `jekyll build`.
for (const dir of ["ai", "vision", "math"]) {
  if (fs.existsSync(dir)) findPages(dir, pages);
}
for (const file of ["index.md", "404.html"]) {
  if (fs.existsSync(file)) pages.push(file);
}

const changed = [];
const skipped = [];

for (const file of pages) {
  let src = fs.readFileSync(file, "utf8");
  if (!/<main[\s>]/.test(src)) { skipped.push([file, "no <main> to target"]); continue; }
  if (/<main[^>]*\bid="main"/.test(src)) continue;

  const next = src.replace(/<main(\s[^>]*)?>/, (full, attrs) => {
    const existing = (attrs || "").replace(/\s+$/, "");
    return '<main' + existing + ' id="main">';
  });
  if (next === src) { skipped.push([file, "no bare <main> tag found"]); continue; }
  changed.push({ file, out: next });
}

if (CHECK_ONLY) {
  if (changed.length) {
    console.log("WOULD CHANGE " + changed.length + " page(s)");
    for (const c of changed.slice(0, 10)) console.log("  " + c.file);
    process.exit(1);
  }
  console.log("PASS: every content page has id=\"main\"");
} else {
  for (const c of changed) fs.writeFileSync(c.file, c.out);
  console.log("Added id=\"main\" to " + changed.length + " built page(s).");
  const byReason = {};
  for (const [f, r] of skipped) byReason[r] = (byReason[r] || 0) + 1;
  for (const r in byReason) console.log("  skipped " + byReason[r] + ": " + r);
}
